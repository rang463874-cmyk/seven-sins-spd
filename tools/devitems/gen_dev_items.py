#!/usr/bin/env python3
"""Regenerate DevItemList.java (the developer-tools item spawner list).

Reads the output of ListItems (one fully-qualified Item class per line) on stdin
and writes core/.../devtools/DevItemList.java. Run tools/devitems/regen.sh instead
of calling this directly.
"""
import os
import sys

PKG = "com.shatteredpixel.shatteredpixeldungeon."
OUT = os.path.join(os.path.dirname(__file__), "..", "..", "core", "src", "main", "java",
                   "com", "shatteredpixel", "shatteredpixeldungeon", "devtools", "DevItemList.java")

# (label, package prefixes relative to PKG) - first match wins, order matters
CATEGORIES = [
    ("근접 무기", ["items.weapon.melee."]),
    ("투척 무기", ["items.weapon.missiles."]),
    ("방어구", ["items.armor."]),
    ("아티팩트", ["items.artifacts."]),
    ("반지", ["items.rings."]),
    ("완드", ["items.wands."]),
    ("포션", ["items.potions."]),
    ("주문서", ["items.scrolls."]),
    ("룬석", ["items.stones."]),
    ("마법/제작", ["items.spells."]),
    ("폭탄", ["items.bombs."]),
    ("음식", ["items.food."]),
    ("씨앗", ["plants."]),
    ("장신구", ["items.trinkets."]),
    ("가방", ["items.bags."]),
    ("퀘스트/열쇠", ["items.quest.", "items.keys."]),
    ("기타", ["items."]),
]

# classes that make no sense to spawn (internal helpers, placeholders)
EXCLUDE = {
    "items.Heap", "items.LostBackpack", "items.weapon.SpiritBow",
    "items.armor.ClassArmor", "items.Item", "items.Honeypot$ShatteredPot",
    "items.weapon.curses.Explosive$ExplosiveCurseBomb",
}


def main():
    classes = [l.strip() for l in sys.stdin if l.strip().startswith(PKG)]
    buckets = {label: [] for label, _ in CATEGORIES}
    for fq in classes:
        rel = fq[len(PKG):]
        if rel in EXCLUDE or ".journal." in fq or ".remains." in fq:
            continue
        for label, prefixes in CATEGORIES:
            if any(rel.startswith(p) for p in prefixes):
                buckets[label].append(fq)
                break

    lines = [
        "package com.shatteredpixel.shatteredpixeldungeon.devtools;",
        "",
        "/**",
        " * GENERATED by tools/devitems/regen.sh - do not edit by hand.",
        " * First entry of each row is the category label, the rest are Item class names.",
        " */",
        "public final class DevItemList {",
        "",
        "\tprivate DevItemList() {}",
        "",
        "\tpublic static final String[][] CATEGORIES = {",
    ]
    for label, _ in CATEGORIES:
        items = buckets[label]
        if not items:
            continue
        lines.append("\t\t{\"%s\"," % label)
        for fq in items:
            lines.append("\t\t\t\"%s\"," % fq)
        lines.append("\t\t},")
    lines += ["\t};", "}", ""]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    total = sum(len(v) for v in buckets.values())
    print("DevItemList: %d items in %d categories" % (total, sum(1 for v in buckets.values() if v)))


if __name__ == "__main__":
    main()
